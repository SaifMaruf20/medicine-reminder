const PDFDocument = require('pdfkit');

/**
 * Generate Doctor Health Report PDF using PDFKit
 * Streams PDF buffer directly
 */
function generateHealthReportPDF({ user, bpLogs = [], sugarLogs = [], days = 30 }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 40, size: 'A4' });
    const buffers = [];

    doc.on('data', buffers.push.bind(buffers));
    doc.on('end', () => {
      const pdfData = Buffer.concat(buffers);
      resolve(pdfData);
    });
    doc.on('error', reject);

    // ─── Header ───────────────────────────────────────────
    doc
      .fillColor('#059669')
      .fontSize(22)
      .text('OshudhSathi - Patient Health Report', { align: 'center' });

    doc
      .fillColor('#64748B')
      .fontSize(10)
      .text(`Generated on: ${new Date().toLocaleDateString('en-GB')} | Past ${days} Days Report`, { align: 'center' })
      .moveDown(1);

    doc
      .strokeColor('#E2E8F0')
      .lineWidth(1)
      .moveTo(40, doc.y)
      .lineTo(555, doc.y)
      .stroke()
      .moveDown(0.5);

    // ─── Patient Info ─────────────────────────────────────
    doc.fillColor('#1E293B').fontSize(12);
    doc.text(`Patient Name: ${user.name || 'N/A'}`);
    doc.text(`Phone: ${user.phone || 'N/A'}`);
    doc.text(`Blood Group: ${user.blood_group || 'N/A'}`);
    if (user.chronic_conditions) {
      doc.text(`Chronic Conditions: ${user.chronic_conditions}`);
    }
    doc.moveDown(1);

    // ─── Blood Pressure Section ───────────────────────────
    doc
      .fillColor('#059669')
      .fontSize(14)
      .text(`Blood Pressure Logs (${bpLogs.length} Records)`)
      .moveDown(0.5);

    if (bpLogs.length === 0) {
      doc.fillColor('#94A3B8').fontSize(10).text('No Blood Pressure records found for this period.');
    } else {
      doc.fillColor('#334155').fontSize(10);
      bpLogs.slice(0, 15).forEach((log) => {
        const dateStr = new Date(log.recorded_at).toLocaleDateString('en-GB');
        const reading = `${log.value_1}/${log.value_2} ${log.unit || 'mmHg'}`;
        const note = log.notes ? `(${log.notes})` : '';
        doc.text(`• ${dateStr}: ${reading} ${note}`);
      });
      if (bpLogs.length > 15) {
        doc.text(`... and ${bpLogs.length - 15} more records.`);
      }
    }
    doc.moveDown(1);

    // ─── Blood Sugar Section ──────────────────────────────
    doc
      .fillColor('#059669')
      .fontSize(14)
      .text(`Blood Sugar Logs (${sugarLogs.length} Records)`)
      .moveDown(0.5);

    if (sugarLogs.length === 0) {
      doc.fillColor('#94A3B8').fontSize(10).text('No Blood Sugar records found for this period.');
    } else {
      doc.fillColor('#334155').fontSize(10);
      sugarLogs.slice(0, 15).forEach((log) => {
        const dateStr = new Date(log.recorded_at).toLocaleDateString('en-GB');
        const context = log.meal_context ? `[${log.meal_context}]` : '';
        const reading = `${log.value_1} ${log.unit || 'mmol/L'}`;
        const note = log.notes ? `(${log.notes})` : '';
        doc.text(`• ${dateStr}: ${reading} ${context} ${note}`);
      });
      if (sugarLogs.length > 15) {
        doc.text(`... and ${sugarLogs.length - 15} more records.`);
      }
    }
    doc.moveDown(1.5);

    // ─── Footer / Disclaimer ──────────────────────────────
    doc
      .strokeColor('#E2E8F0')
      .lineWidth(1)
      .moveTo(40, doc.y)
      .lineTo(555, doc.y)
      .stroke()
      .moveDown(0.5);

    doc
      .fillColor('#94A3B8')
      .fontSize(8)
      .text(
        'Disclaimer: This report is automatically generated by OshudhSathi based on user-entered logs. Please consult a qualified medical professional for diagnosis and prescription adjustments.',
        { align: 'center' }
      );

    doc.end();
  });
}

module.exports = { generateHealthReportPDF };
